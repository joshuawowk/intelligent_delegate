const reps = cfg.reps || 5

function buildRuns() {
  const runs = []
  if (cfg.pilot) {
    for (const p of PILOT) runs.push({ task: p[0], model: p[1], effort: p[2], rep: 1 })
  } else {
    for (const task of TASKS) {
      for (const arm of ARMS) {
        for (let rep = 1; rep <= reps; rep++) runs.push({ task: task, model: arm[0], effort: arm[1], rep: rep })
      }
    }
    // Deterministic shuffle: drift in API latency over the sweep should land on every arm
    // equally. Math.random() is unavailable in a workflow, so this is a fixed-seed LCG.
    let seed = 20261009
    const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296 }
    for (let i = runs.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1))
      const t = runs[i]; runs[i] = runs[j]; runs[j] = t
    }
  }
  for (const r of runs) {
    r.id = r.task + '-' + r.model + '-' + r.effort + '-' + r.rep
    r.dir = cfg.root + '/' + r.id + '/work'
  }
  return runs
}

function prompt(r) {
  return [
    'RUN_ID: ' + r.id,
    '',
    'Your working directory for this task is:',
    '  ' + r.dir,
    'Everything you need is inside it. Work only there: do not read, list or search anything',
    'outside that directory, including the directory you started in.',
    'Do not call the advisor tool on this task.',
    '',
    BRIEFS[r.task],
    'Return through the structured output, and set run_id to the RUN_ID above.',
  ].join('\n')
}

const runs = buildRuns()
log((cfg.pilot ? 'PILOT: ' : 'SWEEP: ') + runs.length + ' runs under ' + cfg.root + (cfg.pilot ? '' : ' — ' + reps + ' reps x ' + ARMS.length + ' arms x ' + TASKS.length + ' tasks. Well above the default 10-agent guideline, deliberately: the tier defaults this sets govern every later fan-out, and runs take seconds.'))

