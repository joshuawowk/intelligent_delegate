#!/usr/bin/env python3
"""Write sweep.workflow.js with the task briefs from briefs.json embedded.

    python3 make_workflow.py

A Workflow script has no filesystem access, so the briefs have to be inside it. They are
generated here rather than pasted so that briefs.json stays the single source: rebuild
the fixtures, re-run this, and the script cannot drift from what the graders expect.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = r'''export const meta = {
  name: 'tier-sweep',
  description: 'Run four graded task shapes across model x effort arms to measure speed, quality and cost',
  phases: [
    { title: 't1 transform', detail: '40 records specified by example' },
    { title: 't2 extract', detail: 'ten questions over a 2,400-line log' },
    { title: 't3 review', detail: 'eight seeded defects against a numbered spec' },
    { title: 't4 implement', detail: 'three functions against hidden tests' },
    { title: 'Fixture review', detail: 'pilot only: hunt for ambiguity before the sweep spends agents on it' },
  ],
}

// GENERATED by make_workflow.py from briefs.json — edit that, not this.
const BRIEFS = __BRIEFS__

const TASKS = ['t1', 't2', 't3', 't4']
const PHASE = { t1: 't1 transform', t2: 't2 extract', t3: 't3 review', t4: 't4 implement' }
// The shipped definition whose tool surface, system prompt and maxTurns each run borrows.
// Model and effort are overridden per arm; holding the definition fixed within a task is
// what makes two arms of that task comparable.
const TASK_AGENT = {
  t1: 'intelligent-delegate:worker',
  t2: 'intelligent-delegate:inspector',
  t3: 'intelligent-delegate:inspector',
  t4: 'intelligent-delegate:worker',
}
const ARMS = [
  ['haiku', 'low'], ['haiku', 'medium'], ['haiku', 'high'],
  ['sonnet', 'low'], ['sonnet', 'medium'], ['sonnet', 'high'],
  ['opus', 'medium'], ['opus', 'high'],
]
// What `mechanical` actually ran at before 0.4.0 in an xhigh session: no effort declared.
const EXTRA = { t1: [['haiku', 'xhigh']] }
const PILOT = [['t1', 'haiku', 'low'], ['t2', 'haiku', 'low'], ['t3', 'opus', 'medium'], ['t4', 'sonnet', 'low']]

const RUN_ID = { type: 'string' }
const SCHEMA = {
  t1: {
    type: 'object',
    properties: {
      run_id: RUN_ID,
      output_path: { type: 'string' },
      lines_written: { type: 'integer' },
      method: { type: 'string', enum: ['script', 'manual', 'mixed'] },
    },
    required: ['run_id', 'output_path', 'lines_written', 'method'],
  },
  t2: {
    type: 'object',
    properties: {
      run_id: RUN_ID,
      q1: { type: 'integer' }, q2: { type: 'string' }, q3: { type: 'string' }, q4: { type: 'string' },
      q5: { type: 'string' }, q6: { type: 'string' }, q7: { type: 'string' }, q8: { type: 'integer' },
      q9: { type: 'string' }, q10: { type: 'integer' },
    },
    required: ['run_id', 'q1', 'q2', 'q3', 'q4', 'q5', 'q6', 'q7', 'q8', 'q9', 'q10'],
  },
  t3: {
    type: 'object',
    properties: {
      run_id: RUN_ID,
      findings: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            line: { type: 'integer' },
            clause: { type: 'integer' },
            description: { type: 'string' },
          },
          required: ['line', 'clause', 'description'],
        },
      },
    },
    required: ['run_id', 'findings'],
  },
  t4: {
    type: 'object',
    properties: {
      run_id: RUN_ID,
      solution_path: { type: 'string' },
      self_check: { type: 'string' },
    },
    required: ['run_id', 'solution_path', 'self_check'],
  },
}

const REVIEW = {
  type: 'object',
  properties: {
    issues: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          task: { type: 'string' },
          severity: { type: 'string', enum: ['blocking', 'minor'] },
          where: { type: 'string' },
          problem: { type: 'string' },
          fix: { type: 'string' },
        },
        required: ['task', 'severity', 'where', 'problem', 'fix'],
      },
    },
    verdict: { type: 'string' },
  },
  required: ['issues', 'verdict'],
}

const cfg = args || {}
if (!cfg.root) throw new Error('args.root is required: the directory make_runs.py laid the runs out under')
const reps = cfg.reps || 3

function buildRuns() {
  const runs = []
  if (cfg.pilot) {
    for (const p of PILOT) runs.push({ task: p[0], model: p[1], effort: p[2], rep: 1 })
  } else {
    for (const task of TASKS) {
      for (const arm of ARMS.concat(EXTRA[task] || [])) {
        for (let rep = 1; rep <= reps; rep++) runs.push({ task: task, model: arm[0], effort: arm[1], rep: rep })
      }
    }
    // Deterministic shuffle: drift in API latency over the sweep should land on every arm
    // equally. Math.random() is unavailable in a workflow, so this is a fixed-seed LCG.
    let seed = 20261009
    const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296 }
    for (let i = runs.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1))
      const t = runs[i]; runs[i] = runs[j]; runs[j] = t
    }
  }
  for (const r of runs) {
    r.id = r.task + '-' + r.model + '-' + r.effort + '-' + r.rep
    r.dir = cfg.root + '/' + r.id + '/work'
  }
  return runs
}

function prompt(r) {
  return [
    'RUN_ID: ' + r.id,
    '',
    'Your working directory for this task is:',
    '  ' + r.dir,
    'Everything you need is inside it. Work only there: do not read, list or search anything',
    'outside that directory, including the directory you started in.',
    'Do not call the advisor tool on this task.',
    '',
    BRIEFS[r.task],
    'Return through the structured output, and set run_id to the RUN_ID above.',
  ].join('\n')
}

const runs = buildRuns()
log((cfg.pilot ? 'PILOT: ' : 'SWEEP: ') + runs.length + ' runs under ' + cfg.root + (cfg.pilot ? '' : ' — ' + reps + ' reps x ' + ARMS.length + ' arms x ' + TASKS.length + ' tasks, plus haiku/xhigh on t1. Well above the default 10-agent guideline, deliberately: the tier defaults this sets govern every later fan-out.'))

const sweep = pipeline(
  runs,
  r => agent(prompt(r), {
    agentType: TASK_AGENT[r.task],
    model: r.model,
    effort: r.effort,
    label: r.id,
    phase: PHASE[r.task],
    schema: SCHEMA[r.task],
  }).then(res => ({ id: r.id, returned: res !== null && res !== undefined, echoed: res ? res.run_id === r.id : false })),
)

let review = null
if (cfg.pilot) {
  review = agent([
    'You are checking measurement fixtures before about a hundred agent runs are spent on them.',
    'A flaw here silently corrupts every result built on it, so be adversarial.',
    '',
    'Directory: /home/jwowk/Repos/intelligent_delegate/evals/tier-sweep  (frozen at commit ' + (cfg.sha || 'HEAD') + '; do not modify anything)',
    '  briefs.json       the exact task text each agent is given',
    '  fixtures/t1..t4   the files each agent sees',
    '  keys/             the answer keys',
    '  src/              reference implementations, hidden tests, the seeded mutations',
    '  analyze.py        the graders',
    '  build_fixtures.py the generator',
    '',
    'Four tasks: t1 transform records by example; t2 answer ten questions from a log; t3 review ledger.py',
    'against SPEC.md for seeded defects; t4 implement solution.py against SPEC.md, graded by hidden tests.',
    '',
    'Find, for each task:',
    '  1. AMBIGUITY — any brief sentence, question or spec clause where two readings survive a careful read and',
    '     the key rewards only one. Quote it and give both readings.',
    '  2. WRONG KEYS — any answer in keys/ that the fixture does not support. Recompute independently; do not',
    '     trust the generator. For t2, re-derive every answer from fixtures/t2/service.log with your own commands.',
    '  3. UNENTAILED TESTS — any hidden test in src/hidden_tests.py whose expected behaviour SPEC.md does not',
    '     determine, so a correct reading of the spec could fail it.',
    '  4. GRADER FLAWS — any way analyze.py marks a correct answer wrong, or a wrong answer right. For t3,',
    '     consider a reviewer who cites the def line, the raise line, or the right line with the wrong clause.',
    '  5. SEEDED DEFECTS in t3 that are not really contradicted by SPEC.md, and REAL defects in the reference',
    '     (src/ledger_ok.py) that a good reviewer would rightly report and the grader would count as noise.',
    '',
    'severity blocking = it would change a score or a ranking; minor = cosmetic. Report only what you can',
    'demonstrate, with the command or the quoted text. An empty issues list is a fine answer if the fixtures hold.',
    'verdict: one sentence — safe to run the sweep on, or not.',
  ].join('\n'), {
    agentType: 'intelligent-delegate:reviewer',
    label: 'fixture-review',
    phase: 'Fixture review',
    schema: REVIEW,
  })
}

const done = (await sweep).filter(Boolean)
const reviewed = review ? await review : null
const noReturn = done.filter(d => !d.returned).map(d => d.id)
const died = runs.length - done.length
if (died) log('WARNING: ' + died + ' run(s) died or were skipped and are missing from the results')
if (noReturn.length) log('WARNING: ' + noReturn.length + ' run(s) returned nothing: ' + noReturn.join(', '))

return {
  runs: runs.length,
  completed: done.length,
  returned: done.filter(d => d.returned).length,
  run_id_echoed: done.filter(d => d.echoed).length,
  no_return: noReturn,
  review: reviewed,
}
'''


def main():
    with open(os.path.join(HERE, "briefs.json")) as fh:
        briefs = json.load(fh)
    js = TEMPLATE.replace("__BRIEFS__", json.dumps(briefs, indent=2, ensure_ascii=True))
    out = os.path.join(HERE, "sweep.workflow.js")
    with open(out, "w") as fh:
        fh.write(js)
    print("wrote %s (%d bytes)" % (out, len(js)))


if __name__ == "__main__":
    main()
