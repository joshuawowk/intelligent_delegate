#!/usr/bin/env python3
"""Write RESULTS.md from results/raw.json.

    python3 results_md.py

Every figure in RESULTS.md is computed here from the graded runs. Nothing in that file is
typed by hand, so a number there can be traced to a row in raw.json and from there to a
transcript.
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = json.load(open(os.path.join(HERE, "results", "raw.json")))["rows"]
good = [r for r in rows if not r["excluded"]]
MODELS, EFFORTS, TASKS = ("haiku", "sonnet", "opus"), ("low", "medium", "high", "xhigh"), ("t1", "t2", "t3", "t4")
NAME = {"t1": "t1 transform", "t2": "t2 extract", "t3": "t3 review", "t4": "t4 implement"}

cell = collections.defaultdict(list)
for r in good:
    cell[(r["task"], r["model"], r["effort"])].append(r)


def stat(task, model, effort, key):
    sel = cell[(task, model, effort)]
    if key == "min":
        return min(r["score"] for r in sel)
    if key == "out":
        return sum(r["tokens"]["out"] for r in sel) / len(sel)
    if key == "think":
        return sum(r["tokens"]["think"] for r in sel) / len(sel)
    return sum(r[key] for r in sel) / len(sel)


def over(model, effort, key):
    """Mean of the four per-task means: every task weighs the same."""
    return sum(stat(t, model, effort, key) for t in TASKS) / len(TASKS)


def x(a, b):
    return "%.1fx" % (a / b)


L = []
w = L.append
n_runs, n_void = len(rows), len(rows) - len(good)
total_cost = sum(r["cost_usd"] for r in rows)
by_model = {m: sum(r["cost_usd"] for r in rows if r["model"] == m) for m in MODELS}
advisor = collections.Counter(tuple(r["advisor_model"]) for r in rows)
adv_calls = sum(r["advisor_calls"] for r in rows)
reps = sorted(set(len(v) for v in cell.values()))

w("# Tier sweep — results")
w("")
w("Generated by `results_md.py` from `results/raw.json`. Do not edit by hand; re-run it.")
w("")
w("**Run 2026-10-09** on Claude Code 2.1.295, from a `claude-opus-5-5` session at `xhigh`.")
w("%d runs: %d arms x %d tasks x %s reps. **%d void.** Every run had the session's advisor"
  % (n_runs, len(MODELS) * len(EFFORTS), len(TASKS), "/".join(str(k) for k in reps), n_void))
w("(`%s`) attached, was told not to call it, and none did (%d calls)."
  % (", ".join(a[0] for a in advisor), adv_calls))
w("The whole sweep billed **$%.2f** — Haiku $%.2f, Sonnet $%.2f, Opus $%.2f."
  % (total_cost, by_model["haiku"], by_model["sonnet"], by_model["opus"]))
w("")
w("Read `README.md` for the method and its limits, and `DECISIONS.md` for the rules below,")
w("which were committed before this ran.")
w("")
w("## The grid")
w("")
w("Mean of the four per-task means, so each task weighs the same. Score is each task's")
w("grader output in [0, 1]; seconds are first transcript record to last; dollars are priced")
w("from per-request usage.")
w("")
w("| arm | score | seconds | cost $ | output tokens |")
w("|---|--:|--:|--:|--:|")
for m in MODELS:
    for e in EFFORTS:
        w("| `%s/%s` | %.3f | %.1f | %.4f | %.0f |" % (m, e, over(m, e, "score"), over(m, e, "seconds"),
                                                       over(m, e, "cost_usd"), over(m, e, "out")))
w("")
sm = ("sonnet", "medium")
w("## What it shows")
w("")
w("**1. Quality is at or near the ceiling in every cell.** The lowest overall score is %.3f"
  % min(over(m, e, "score") for m in MODELS for e in EFFORTS))
w("(`haiku/low`). On bounded work with a checkable answer, every current model at every")
w("effort mostly gets it right. This sweep therefore ranks cells by **time and money**, and")
w("says little about which is *smarter* — see \"Saturation\" below before leaning on that.")
w("")
w("**2. Effort is the largest speed lever, larger than model.** Against the same model at")
w("`medium`, `xhigh` took %s as long on Haiku, %s on Sonnet and %s on Opus. Sonnet and Opus scored the same at both."
  % (x(over("haiku", "xhigh", "seconds"), over("haiku", "medium", "seconds")),
     x(over("sonnet", "xhigh", "seconds"), over("sonnet", "medium", "seconds")),
     x(over("opus", "xhigh", "seconds"), over("opus", "medium", "seconds"))))
w("`high` took %s, %s and %s."
  % (x(over("haiku", "high", "seconds"), over("haiku", "medium", "seconds")),
     x(over("sonnet", "high", "seconds"), over("sonnet", "medium", "seconds")),
     x(over("opus", "high", "seconds"), over("opus", "medium", "seconds"))))
w("")
w("**3. `low` saves almost nothing over `medium` and is where the misses are.** `low` was")
w("%.0f%%, %.0f%% and %.0f%% faster than `medium` (Haiku, Sonnet, Opus). Every miss by Sonnet or"
  % tuple(100 * (1 - over(m, "low", "seconds") / over(m, "medium", "seconds")) for m in MODELS))
w("Opus in the whole sweep happened at `low`. From `medium` up, both were perfect on all")
w("four tasks.")
w("")
w("**4. Sonnet is the fast model. Haiku is the cheap one.** At `medium`, Haiku took %s as"
  % x(over("haiku", "medium", "seconds"), over("sonnet", "medium", "seconds")))
w("long as Sonnet and cost %s less. Haiku is slower because it writes more: %.0f output tokens"
  % (x(over("sonnet", "medium", "cost_usd"), over("haiku", "medium", "cost_usd")), over("haiku", "medium", "out")))
w("a run against Sonnet's %.0f, %s as many. That is also why its measured cost advantage is"
  % (over("sonnet", "medium", "out"), x(over("haiku", "medium", "out"), over("sonnet", "medium", "out"))))
w("about %s where its price sheet says 20x."
  % x(over("sonnet", "medium", "cost_usd"), over("haiku", "medium", "cost_usd")))
w("")
w("**5. Opus bought nothing here.** At `medium` it took %s as long as Sonnet and cost %s as"
  % (x(over("opus", "medium", "seconds"), over("sonnet", "medium", "seconds")),
     x(over("opus", "medium", "cost_usd"), over("sonnet", "medium", "cost_usd"))))
w("much for the same score. None of these tasks is the kind Opus is for.")
w("")
w("**6. An untiered subagent in this session is the slowest cell on the grid.** A subagent")
w("that names no tier inherits the session's model and effort — here `opus/xhigh`. Against")
w("`sonnet/medium` that is **%s the time and %s the cost** for the same score."
  % (x(over("opus", "xhigh", "seconds"), over(*sm, "seconds")), x(over("opus", "xhigh", "cost_usd"), over(*sm, "cost_usd"))))
w("")
w("## Measured effort multipliers")
w("")
w("Each model against its own `high`, mean of per-task means. This replaces the effort-cost")
w("index 0.3.0 reasoned from, which described Sonnet 5 and Opus 5; no 5.5 model publishes one.")
w("It is a measurement on four tasks, not a constant.")
w("")
w("| model | | low | medium | high | xhigh |")
w("|---|---|--:|--:|--:|--:|")
for m in MODELS:
    for key, label in (("cost_usd", "cost"), ("seconds", "time")):
        w("| %s | %s | %s |" % (m if key == "cost_usd" else "", label,
                                " | ".join("%.2f" % (over(m, e, key) / over(m, "high", key)) for e in EFFORTS)))
w("")
w("0.3.0 said `sonnet/xhigh` and `opus/high` cost about the same. Measured here:")
w("`sonnet/xhigh` $%.4f and %.1f s, `opus/high` $%.4f and %.1f s — Sonnet at `xhigh` is cheaper"
  % (over("sonnet", "xhigh", "cost_usd"), over("sonnet", "xhigh", "seconds"),
     over("opus", "high", "cost_usd"), over("opus", "high", "seconds")))
w("and slower, and both are far behind `sonnet/medium` on each axis.")
w("")
w("## Per task")
for t in TASKS:
    w("")
    w("### %s" % NAME[t])
    w("")
    w("| arm | n | score | min | seconds | cost $ | output | thinking | requests (max) |")
    w("|---|--:|--:|--:|--:|--:|--:|--:|--:|")
    for m in MODELS:
        for e in EFFORTS:
            sel = cell[(t, m, e)]
            w("| `%s/%s` | %d | %.3f | %.3f | %.1f | %.4f | %.0f | %.0f | %.1f (%d) |" % (
                m, e, len(sel), stat(t, m, e, "score"), stat(t, m, e, "min"), stat(t, m, e, "seconds"),
                stat(t, m, e, "cost_usd"), stat(t, m, e, "out"), stat(t, m, e, "think"),
                stat(t, m, e, "requests"), max(r["requests"] for r in sel)))

# ---- misses
w("")
w("## Every miss")
w("")
t2miss = collections.defaultdict(collections.Counter)
t3miss = collections.defaultdict(collections.Counter)
for r in good:
    arm = "%s/%s" % (r["model"], r["effort"])
    if r["task"] == "t2":
        for q in r["detail"].get("wrong", []):
            t2miss[arm][q] += 1
    if r["task"] == "t3":
        for b in r["detail"].get("missed", []):
            t3miss[arm][b] += 1
t1bad = [r["id"] for r in good if r["task"] == "t1" and r["score"] < 1]
t4bad = [r["id"] for r in good if r["task"] == "t4" and r["score"] < 1]
w("- **t1, t4:** %s." % ("none — all %d runs of each scored 1.000" % len([r for r in good if r["task"] == "t1"])
                         if not t1bad and not t4bad else "t1 %s; t4 %s" % (t1bad, t4bad)))
w("- **t2:** %s. Every one is the same question — the message on the line *after* a named"
  % "; ".join("`%s` %s" % (a, ", ".join("%s x%d" % kv for kv in v.items())) for a, v in t2miss.items()))
w("  entry. The run's own search printed both lines and it reported the wrong one. No other")
w("  model missed any t2 question.")
bugs = {b["id"]: b for b in json.load(open(os.path.join(HERE, "keys", "t3_bugs.json")))["bugs"]}
w("- **t3:** %s." % "; ".join("`%s` %s" % (a, ", ".join("%s x%d" % kv for kv in v.items())) for a, v in t3miss.items()))
for b in sorted(set(k for v in t3miss.values() for k in v), key=lambda s: int(s[1:])):
    w("  - %s (%s) — %s." % (b, bugs[b]["difficulty"], bugs[b]["desc"]))
um = [(r["id"], u) for r in good if r["task"] == "t3" for u in r["detail"]["unmatched"]]
dups = sum(r["detail"]["duplicates"] for r in good if r["task"] == "t3")
nf = sum(r["detail"]["findings"] for r in good if r["task"] == "t3")
w("  Of %d findings across the %d review runs, %d earned no credit and %d were duplicates."
  % (nf, len([r for r in good if r["task"] == "t3"]), len(um), dups))
for rid, u in um:
    w("  The uncredited one, `%s`: \"%s\" — %s. Read per the audit rule: it is a seeded"
      % (rid, u["description"][:80].rsplit(" ", 1)[0] + "...", u["why"].split(" (")[0]))
    w("  defect described correctly with a repro that asserts the wrong value, not a flaw in the")
    w("  fixture. No reviewer padded its report.")

# ---- decisions
w("")
w("## The pre-registered rules, applied")
w("")
s = lambda t, m, e, k: stat(t, m, e, k)
w("**D1 — `mechanical` gets `effort: low`.** `haiku/low` on t1: mean %.3f, min %.3f, against"
  % (s("t1", "haiku", "low", "score"), s("t1", "haiku", "low", "min")))
w("a bar of 0.98 and 0.95. The tier declared no effort and so ran at the session's:")
w("`haiku/xhigh` took %.1f s and $%.4f on t1 where `haiku/low` took %.1f s and $%.4f — **%s"
  % (s("t1", "haiku", "xhigh", "seconds"), s("t1", "haiku", "xhigh", "cost_usd"),
     s("t1", "haiku", "low", "seconds"), s("t1", "haiku", "low", "cost_usd"),
     x(s("t1", "haiku", "xhigh", "seconds"), s("t1", "haiku", "low", "seconds"))))
w("faster** at the same score.")
w("")
best_s = min(EFFORTS, key=lambda e: (-s("t2", "sonnet", e, "score"), s("t2", "sonnet", e, "cost_usd")))
w("**D2 — a read-only Haiku tier is added, at `low`.** On t2 every Sonnet arm scored %.3f; the"
  % s("t2", "sonnet", best_s, "score"))
w("cheapest of them is `sonnet/%s` at $%.4f and %.1f s. `haiku/low` scored %.3f (min %.3f) —"
  % (best_s, s("t2", "sonnet", best_s, "cost_usd"), s("t2", "sonnet", best_s, "seconds"),
     s("t2", "haiku", "low", "score"), s("t2", "haiku", "low", "min")))
w("within 0.05, min above 0.80 — at $%.4f, **%s cheaper**. It qualifies on cost, not on speed:"
  % (s("t2", "haiku", "low", "cost_usd"), x(s("t2", "sonnet", best_s, "cost_usd"), s("t2", "haiku", "low", "cost_usd"))))
w("at %.1f s it is slower than that Sonnet arm. The rule was written expecting Haiku to be"
  % s("t2", "haiku", "low", "seconds"))
w("the fast option. It is the cheap one, and the tier is described that way.")
w("")
w("**D3 — `inspector` moves from `high` to `medium`. Saturated.** On t3 `sonnet/medium` and")
w("`sonnet/high` both scored %.3f and both found every hard defect in every rep; `medium`"
  % s("t3", "sonnet", "medium", "score"))
w("took %.1f s against %.1f s, **%.0f%% faster**, at $%.4f against $%.4f. The rule is met, and it is"
  % (s("t3", "sonnet", "medium", "seconds"), s("t3", "sonnet", "high", "seconds"),
     100 * (1 - s("t3", "sonnet", "medium", "seconds") / s("t3", "sonnet", "high", "seconds")),
     s("t3", "sonnet", "medium", "cost_usd"), s("t3", "sonnet", "high", "cost_usd")))
w("met on a **saturated** task: this shows `medium` is enough for a bounded check of an")
w("artifact against its source, and shows nothing about review harder than that.")
w("`haiku/medium` also scored %.3f on t3. Recorded as a candidate; it changes nothing."
  % s("t3", "haiku", "medium", "score"))
w("")
f1 = 100 * (1 - s("t1", "sonnet", "medium", "seconds") / s("t1", "sonnet", "high", "seconds"))
f4 = 100 * (1 - s("t4", "sonnet", "medium", "seconds") / s("t4", "sonnet", "high", "seconds"))
w("**D4 — `worker` and `drafter` are unchanged.** `worker` (`sonnet/medium`): `sonnet/low` is")
w("not 20%% faster on either task (t1 %.1f s against %.1f s; t4 %.1f s against %.1f s)."
  % (s("t1", "sonnet", "low", "seconds"), s("t1", "sonnet", "medium", "seconds"),
     s("t4", "sonnet", "low", "seconds"), s("t4", "sonnet", "medium", "seconds")))
w("`drafter` (`sonnet/high`): `sonnet/medium` matches its score on both tasks and is %.0f%% faster"
  % f4)
w("on t4 but only %.0f%% faster on t1. The rule asked for 20%% on both, so `drafter` stays at" % f1)
w("`high` and `medium` is a **candidate**. The rule's wording left open whether 20% had to")
w("hold on each task or overall; it is read the stricter way, since that is the direction")
w("every rule in `DECISIONS.md` leans.")
w("")
w("**D5 — `reviewer` and `builder` are unchanged**, as the rule said they would be whatever")
w("was measured. For the record, `opus/high` against `opus/medium`: t3 %.1f s against %.1f s,"
  % (s("t3", "opus", "high", "seconds"), s("t3", "opus", "medium", "seconds")))
w("t4 %.1f s against %.1f s, same scores. That is the price of an escalation on work that did"
  % (s("t4", "opus", "high", "seconds"), s("t4", "opus", "medium", "seconds")))
w("not need one, which is the reason to escalate only on a predicate.")
w("")
w("**D6 — `judge`** was not measured and stays `opus/xhigh`.")
w("")
w("## Saturation")
w("")
sat = sum(1 for t in TASKS for m in MODELS for e in EFFORTS if s(t, m, e, "score") >= 0.98)
w("%d of the %d task x arm cells scored 0.98 or better. That is the main limit on what this"
  % (sat, len(TASKS) * len(MODELS) * len(EFFORTS)))
w("sweep can support. It is strong evidence about **time and cost**, where the cells differ")
w("by multiples and the runs agree closely. It is weak evidence about **quality**, where")
w("almost nothing separates them: it shows the cheaper cells are sufficient for bounded,")
w("checkable work, and it cannot show where they stop being sufficient. The tier defaults")
w("that moved (D1, D2, D3) moved on those terms. The escalation predicates did not move at")
w("all, and nothing here is a reason to loosen them.")
w("")
w("## Turn counts")
w("")
w("Most API requests any single run made, for sizing `maxTurns`:")
w("")
w("| task | haiku | sonnet | opus |")
w("|---|--:|--:|--:|")
for t in TASKS:
    w("| %s | %s |" % (NAME[t], " | ".join(str(max(r["requests"] for r in good if r["task"] == t and r["model"] == m)) for m in MODELS)))
w("")
mx = lambda t, m, e: max(r["requests"] for r in cell[(t, m, e)])
w("No run reached the cap of the definition it borrowed (`worker` 25, `inspector` 50). One")
w("number bears on a cap that was not in play: Haiku made up to %d requests on t2 at `high`"
  % max(mx("t2", "haiku", "high"), mx("t2", "haiku", "xhigh")))
w("and `xhigh`, against %d at `low`. `mechanical`'s cap is 12, so a Haiku tier meant for"
  % mx("t2", "haiku", "low"))
w("reading should not inherit it. These are short tasks; the 2026-09-30 measurements in")
w("`../../skills/delegate/references/agent-catalog.md` remain the evidence for the other caps.")

open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print("wrote RESULTS.md: %d lines" % len(L))
